/**
 * 穩定字串 hash（FNV-1a 32-bit）：同輸入永遠同輸出。
 * 不可改成亂數——worker 補寫 DB、DO fallback、前端顯示三處要選到同一個名字。
 */
function hashStr(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/** 依 uid 穩定指派自動暱稱（新用戶 / 從未改名者的系統代號） */
export function autoNickname(uid: number): string {
  return NICKNAME_POOL[hashStr(`nick:${uid}`) % NICKNAME_POOL.length];
}

/** 依 uid + 陀螺類型穩定指派陀螺名（同人同類型永遠同名） */
export function beybladeName(uid: number, type: string): string {
  return BEYBLADE_POOL[hashStr(`bey:${uid}:${type}`) % BEYBLADE_POOL.length];
}
